"""Folders of symlinks for browsing a recipe directory.

A recipe directory is flat on purpose: a recipe can be in any number of
categories, and Paprika never sees folders.  For browsing in a file manager,
`paprika-recipes views` builds a separate tree of symlinks instead:

    views/<Category>/     one folder per category, including empty ones
    views/Uncategorized/  recipes with no category
    views/Favorites/      recipes marked as favorites
    views/Pinned/         pinned recipes
    views/Top Rated/      rated recipes, named "5★ Name.md" and so on
    views/Photos/<Name>/  a recipe's gallery photos, named "1 Caption.jpg"
                          and so on in gallery order (just its thumbnail, for
                          a recipe with no gallery)

Every recipe folder also links `attachments/`, so that photo embeds still
resolve when a recipe is opened through a view.  The tree is derived entirely
from the recipe files, their photos and the category list, so it is deleted
and rebuilt from scratch every time.  A marker file inside it is what makes
that deletion safe: a folder without one is never removed.

The output folder has to be excluded by `.paprikaignore`, since the symlinked
recipes in it would otherwise be read as second copies of every recipe.
"""

from __future__ import annotations

import shutil
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import Final

from .exceptions import PaprikaUserError
from .ignore import IGNORE_FILENAME
from .markdown import ATTACHMENTS_DIRNAME
from .remote import RemoteRecipe
from .repository import Repository

DEFAULT_VIEWS_DIRNAME: Final = "views"
MARKER: Final = ".generated-by-paprika-recipes"

UNCATEGORIZED: Final = "Uncategorized"
FAVORITES: Final = "Favorites"
PINNED: Final = "Pinned"
TOP_RATED: Final = "Top Rated"
PHOTOS: Final = "Photos"

#: Folders every tree has, even when empty, so its shape doesn't change as
#: recipes come and go.
FIXED_FOLDERS: Final = (UNCATEGORIZED, FAVORITES, PINNED, TOP_RATED)

_UNSAFE: Final = '/\\:*?"<>|'


@dataclass(frozen=True)
class ViewsReport:
    """What a build of the tree produced."""

    path: Path
    recipe_links: int
    photo_links: int
    skipped: tuple[str, ...] = ()


def build_views(repository: Repository, output: Path | None = None) -> ViewsReport:
    """Delete and rebuild the views tree; see the module docstring."""
    root = repository.root.resolve()
    views = (output if output is not None else root / DEFAULT_VIEWS_DIRNAME).resolve()

    try:
        relative = views.relative_to(root)
    except ValueError:
        raise PaprikaUserError(f"{views} is not inside the recipe directory {root}.")

    if not relative.parts or relative.parts[0] in (
        ATTACHMENTS_DIRNAME,
        ".paprika",
        ".git",
    ):
        raise PaprikaUserError(f"{views} cannot hold the views.")

    if not repository.ignore.ignores(PurePosixPath(*relative.parts, "recipe.md")):
        raise PaprikaUserError(
            f"Add `{relative.as_posix()}/` to {IGNORE_FILENAME} first; without it "
            "every recipe linked from the views would read as a second copy."
        )

    if views.exists() and not (views / MARKER).exists():
        raise PaprikaUserError(
            f"{views} exists but was not made by this command; move it out of "
            "the way first."
        )

    categories = repository.categories
    folders: dict[str, list[tuple[str, Path]]] = defaultdict(list)
    photos: dict[str, list[tuple[str, Path]]] = {}
    skipped: list[str] = []

    for name in [*categories.names.values(), *FIXED_FOLDERS]:
        folders[_safe_name(name)]

    for path in repository.working_paths():
        try:
            recipe = repository.read_working(path)
        except PaprikaUserError as e:
            skipped.append(str(e))
            continue

        link = path.name
        target = path.resolve().relative_to(root)

        if recipe.categories:
            for uid in recipe.categories:
                folders[_safe_name(categories.display(uid))].append((link, target))
        else:
            folders[UNCATEGORIZED].append((link, target))

        if recipe.on_favorites:
            folders[FAVORITES].append((link, target))

        if recipe.is_pinned:
            folders[PINNED].append((link, target))

        if recipe.rating:
            folders[TOP_RATED].append((f"{recipe.rating}★ {link}", target))

        pictures = _photo_links(root, recipe)

        if pictures:
            photos[_safe_name(path.stem)] = pictures

    shutil.rmtree(views, ignore_errors=True)
    views.mkdir(parents=True)
    (views / MARKER).write_text(
        "Generated by `paprika-recipes views`; deleted and rebuilt on every run.\n",
        encoding="utf-8",
    )

    up = Path(*[".."] * (len(relative.parts) + 1))
    recipe_links = 0

    for folder, entries in sorted(folders.items()):
        directory = views / folder
        directory.mkdir()
        (directory / ATTACHMENTS_DIRNAME).symlink_to(
            up / ATTACHMENTS_DIRNAME, target_is_directory=True
        )

        for name, target in sorted(entries):
            (directory / name).symlink_to(up / target)
            recipe_links += 1

    # A category that happens to be called "Photos" keeps its name; the
    # photo view moves aside instead.
    photos_folder = PHOTOS if PHOTOS not in folders else f"{PHOTOS} (gallery)"
    photo_links = 0

    for recipe_folder, pictures in sorted(photos.items()):
        directory = views / photos_folder / recipe_folder
        directory.mkdir(parents=True)

        for name, target in pictures:
            (directory / name).symlink_to(Path("..", up) / target)
            photo_links += 1

    return ViewsReport(views, recipe_links, photo_links, tuple(skipped))


def _photo_links(root: Path, recipe: RemoteRecipe) -> list[tuple[str, Path]]:
    """Readable names for a recipe's photos, and the attachments they are.

    Gallery photos are numbered in gallery order, which also keeps two with
    the same (or no) caption apart; a caption that is only a number, as the
    app assigns by default, is left off.
    """
    attachments = Path(ATTACHMENTS_DIRNAME)
    entries = [
        (filename, caption)
        for filename, caption in recipe.gallery
        if (root / attachments / filename).is_file()
    ]

    if not entries:
        if recipe.photo and (root / attachments / recipe.photo).is_file():
            suffix = Path(recipe.photo).suffix
            return [(f"thumbnail{suffix}", attachments / recipe.photo)]

        return []

    width = len(str(len(entries)))
    links = []

    for number, (filename, caption) in enumerate(entries, start=1):
        label = caption.strip()
        label = "" if not label or label.isdigit() else _safe_name(label)
        stem = f"{number:0{width}d} {label}".strip()
        links.append((f"{stem}{Path(filename).suffix}", attachments / filename))

    return links


def _safe_name(name: str) -> str:
    cleaned = "".join(c for c in name if c not in _UNSAFE and c.isprintable())

    return cleaned.strip(". ") or "Unnamed"
